"""Regenerate skills/iclone-mcp/references/tool-catalog.md from the LIVE server (iClone running, MCP started).

  python scripts/gen_tool_catalog.py

# CLAUDE-NOTE (2026-10-23): the catalog header always named this script but it was missing from the repo; rebuilt so the
# catalog can't drift from the registry. Module per tool comes from the handler's __module__ (read via python_exec).
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
from icall import call  # noqa: E402

FORK = ("icmcp_extra", "fight_tools", "rlpy2_tools", "texture_doctor")
OUT = os.path.join(os.path.dirname(__file__), "..", "skills", "iclone-mcp", "references", "tool-catalog.md")
SNIPPET = r'''
import sys
m = sys.modules["mc_iclone8_main"]
# the RUNNING server's registry (calling _tool_registry() would reload every module, python_exec included)
srv = getattr(m, "_server", None)
reg = srv.handler.tools if srv is not None and hasattr(srv, "handler") else None
if reg is None:
    reg = next(v.tools for v in vars(srv).values() if hasattr(v, "tools"))
_result = {n: {"module": getattr(t["handler"], "__module__", "?").split(".")[-1], "description": t.get("description", ""),
               "schema": t.get("inputSchema", {})} for n, t in reg.items()}
'''


def main():
    res = call("python_exec", {"code": SNIPPET})
    tools = res["result"] if isinstance(res, dict) and "result" in res else res
    by_mod = {}
    for name, t in sorted(tools.items()):
        by_mod.setdefault(t["module"], []).append((name, t))
    lines = ["# iClone MCP tool catalog (%d tools)" % len(tools), "",
             "Generated by `scripts/gen_tool_catalog.py` from the live server. Do not edit by hand; re-run after adding tools.",
             "Modules %s are the hoodtronik fork's additions; the rest are upstream." % ", ".join("`%s`" % m for m in FORK), ""]
    for mod in sorted(by_mod):
        lines += ["## " + mod, "", "| Tool | Args | What it does |", "|---|---|---|"]
        for name, t in by_mod[mod]:
            props = (t["schema"] or {}).get("properties", {}) or {}
            req = set((t["schema"] or {}).get("required", []) or [])
            args = ", ".join(("**%s**" % a) if a in req else a for a in props)
            desc = " ".join(t["description"].split())
            desc = desc if len(desc) <= 300 else desc[:297] + "..."
            lines.append("| `%s` | %s | %s |" % (name, args, desc.replace("|", "/")))
        lines.append("")
    open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(lines))
    print("wrote %s (%d tools, %d modules)" % (os.path.normpath(OUT), len(tools), len(by_mod)))


if __name__ == "__main__":
    main()
