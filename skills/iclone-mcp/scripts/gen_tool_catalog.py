"""Regenerate references/tool-catalog.md from the LIVE server (iClone running, MCP healthy).

  python skills/iclone-mcp/scripts/gen_tool_catalog.py [--url http://127.0.0.1:8766/mcp]

Groups tools by the tools/*.py module that registers them (found by searching for the quoted tool name), so the
catalog always matches what is actually registered, including tools added since the last run.
"""
import json
import pathlib
import re
import sys
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parents[3]
OUT = pathlib.Path(__file__).resolve().parents[1] / "references" / "tool-catalog.md"
url = sys.argv[sys.argv.index("--url") + 1] if "--url" in sys.argv else "http://127.0.0.1:8766/mcp"

body = json.dumps({"jsonrpc": "2.0", "id": 1, "method": "tools/list"}).encode()
tools = json.load(urllib.request.urlopen(urllib.request.Request(url, body, {"Content-Type": "application/json"}),
                                         timeout=30))["result"]["tools"]
sources = {p.stem: p.read_text(encoding="utf-8", errors="replace") for p in sorted((ROOT / "tools").glob("*.py"))}


def module_of(name):
    for stem, src in sources.items():
        # fork modules: reg("name", ...); upstream modules: registry["name"] = {...}
        if re.search(rf'["\']{re.escape(name)}["\']\s*[,:\]]', src):
            return stem
    return "other"


groups = {}
for t in tools:
    groups.setdefault(module_of(t["name"]), []).append(t)

lines = [f"# iClone MCP tool catalog ({len(tools)} tools)", "",
         "Generated by `scripts/gen_tool_catalog.py` from the live server. Do not edit by hand; re-run after adding tools.",
         "Modules `icmcp_extra`, `fight_tools`, `rlpy2_tools` are the hoodtronik fork's additions; the rest are upstream.", ""]
for mod in sorted(groups):
    lines += [f"## {mod}", "", "| Tool | Args | What it does |", "|---|---|---|"]
    for t in sorted(groups[mod], key=lambda t: t["name"]):
        props = t.get("inputSchema", {}).get("properties", {}) or {}
        req = set(t.get("inputSchema", {}).get("required", []) or [])
        args = ", ".join(f"**{k}**" if k in req else k for k in props)
        desc = " ".join(t.get("description", "").split())
        desc = desc if len(desc) <= 260 else desc[:257] + "..."
        lines.append(f"| `{t['name']}` | {args} | {desc.replace('|', '/')} |")
    lines.append("")
OUT.write_text("\n".join(lines), encoding="utf-8")
print(f"wrote {OUT} ({len(tools)} tools, {len(groups)} modules)")
